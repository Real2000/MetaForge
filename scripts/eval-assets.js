/** 程序化生成干扰块（纯函数、无随机：两次调用输出严格一致——smoke 以此锚定防漂移） */
function makeNoiseChunks() {
  const out = [];
  let i = 0;
  const push = (s) => { out.push({ idx: ++i, content: s }); };
  // 模板 1：系统支持配置（「支持/配置」高频——攻击原句的「它支持/怎么配置」类通用词）
  for (const d of DEPTS) for (const s of SYSTEMS.slice(0, 5)) for (const f of FEATURES.slice(0, 4)) {
    push(`${d}的${s}支持${f}配置，管理员可按需调整参数并保存为默认方案。`);
  }
  // 模板 2：假期申请流程（与请假类问句相近，避开年假/病假/调休禁词）
  for (const l of LEAVES) for (const d2 of DAYS) for (const r of ROLES) {
    push(`${l}的申请流程：需在${d2}报备至直属上级，由${r}审核后生效，过期视为放弃。`);
  }
  // 模板 3：费用报销上限（与住宿/打车/补贴类问句相近，避开 500/200/实报实销禁词）
  for (const f2 of FEES) for (const a of AMOUNTS) {
    push(`${f2}报销上限为${a}元每人每季度，需附发票与审批单，预算外部分由本人承担。`);
  }
  // 模板 4：技术构建（与产品类问句相近，避开 PostgreSQL/RLS/SSE 等禁词）
  for (const t of TECHS) for (const f3 of FEATURES.slice(2)) {
    push(`系统采用${t}构建，具备${f3}能力，新环境部署可在十分钟内完成初始化。`);
  }
  // 模板 5：管理规范（与「怎么处理/什么要求」类问句相近）
  for (const tp of TOPICS) for (const d3 of DEPTS) {
    push(`关于${tp}的管理规范：${d3}人员需遵循公司统一要求，违规将按情节轻重处理并记录在案。`);
  }
  // 模板 6：常见问题样式（与「如何/怎么办」类问句相近）
  for (const s2 of SYSTEMS.slice(2)) for (const d4 of DEPTS) {
    push(`常见问题：如何申请${s2}的权限？请联系${d4}对接人填写开通单，一个工作日内生效。`);
  }
  return out;
}

/** 过滤撞禁词的干扰块（防御：生成模板意外命中即丢弃，宁漏勿误） */
function filterNoiseForbidden(noise) {
  const re = new RegExp(FORBIDDEN.join('|'));
  const kept = [];
  let skipped = 0;
  for (const n of noise) {
    if (re.test(n.content)) { skipped++; continue; }
    kept.push(n);
  }
  return { kept, skipped };
}

